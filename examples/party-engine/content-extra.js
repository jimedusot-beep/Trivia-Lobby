function quizFromFact(row, index) {
  const [prompt, correct, a, b, c, explanation] = row;
  const choices = [a, b, c];
  const position = index % 4;
  choices.splice(position, 0, correct);
  return { prompt, choices, correct: position, explanation };
}
const facts = originalFacts.map(quizFromFact);
const math = [];
for (let a = 4; a <= 15; a++) for (let b = 3; b <= 9; b++) {
  // 84 distinct, bounded arithmetic questions with generated verified answers.
  const answer = a * b;
  const distractors = [answer + a, answer + b, answer - b];
  if (new Set([answer, ...distractors]).size !== 4) continue;
  const choices = [String(answer), ...distractors.map(String)];
  const shift = (a + b) % 4;
  const rotated = [...choices.slice(shift), ...choices.slice(0, shift)];
  math.push({
    prompt: "What is " + a + " multiplied by " + b + "?",
    choices: rotated, correct: (4 - shift) % 4,
    explanation: a + " × " + b + " = " + answer + ".",
  });
}
