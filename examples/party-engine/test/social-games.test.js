import test from "node:test";
import assert from "node:assert/strict";
import { Party } from "../engine.js";
import { validateAction } from "../protocol.js";

function fixture(mode, count=20){
 let now=1000,request=0;
 const p=new Party("ABC234",{clock:()=>now,countdownMs:1});
 const ids=Array.from({length:count},(_,i)=>p.join("Guest "+i));
 const act=(actor,type,value)=>{
  const msg={v:1,type,requestId:"social-"+(++request),matchId:p.matchId,revision:p.revision};
  if(value!==undefined)msg.value=value;
  return p.handle(actor,msg);
 };
 act("host","start",mode);
 now+=1;p.tick();
 return {p,ids,act,advance(ms){now+=ms;p.tick();}};
}
test("20-player rooms allow all guests, disallow a 21st and preserve original quiz",()=>{
 const f=fixture("quiz");
 assert.equal(f.p.phase,"question");
 assert.equal(f.p.roster.length,20);
 assert.throws(()=>f.p.join("Extra"));
 assert.ok(!("correct" in f.p.view(f.ids[3]).question));
 for(const id of f.ids)f.act(id,"answer",1);
 assert.equal(f.p.phase,"reveal");
 assert.equal([...f.p.players.values()].reduce((sum,x)=>sum+x.score,0),2000);
});
test("Majority Rules: private votes, 20 participants, ties, idempotency and late requests",()=>{
 const {p,ids,act,advance}=fixture("majority");
 assert.ok(!JSON.stringify(p.view("host")).includes("winners"));
 const old={v:1,type:"respond",value:0,requestId:"repeat-vote",matchId:p.matchId,revision:p.revision};
 p.handle(ids[0],old);
 assert.deepEqual(p.handle(ids[0],old),{requestId:old.requestId,accepted:true});
 assert.throws(()=>act(ids[0],"respond",1),/locked/);
 for(let i=1;i<20;i++)act(ids[i],"respond",i<12?0:1);
 assert.equal(p.phase,"reveal");
 assert.deepEqual(p.view("host").social.counts,[12,8]);
 assert.equal(p.players.get(ids[0]).score,100);
 assert.equal(p.players.get(ids[19]).score,0);
 p.handle(ids[0],old);
 assert.equal(p.players.get(ids[0]).score,100);
 act("host","next");
 assert.equal(p.phase,"question");
 assert.throws(()=>p.handle(ids[1],{...old,requestId:"stale-vote"}),/out of date/);
 for(let i=0;i<20;i++)act(ids[i],"respond",i%2);
 assert.deepEqual(p.view(ids[0]).social.winners,[0,1]);
 assert.equal(p.players.get(ids[19]).score,100);
 advance(1000);
 assert.equal(p.phase,"reveal");
});
test("Who's Most Likely?: cannot vote for self or nonexistent player; highest nominee votes win",()=>{
 const {p,ids,act}=fixture("likely",10);
 assert.throws(()=>act("host","respond",ids[1]),/joined players/);
 assert.throws(()=>act(ids[0],"respond",ids[0]),/another player/);
 assert.throws(()=>act(ids[1],"respond","forged"),/another player/);
 for(let i=0;i<ids.length;i++)act(ids[i],"respond",i===1?ids[2]:ids[1]);
 const reveal=p.view("host").social;
 assert.equal(p.phase,"reveal");
 assert.equal(reveal.counts.find(x=>x.id===ids[1]).count,9);
 assert.equal(p.players.get(ids[0]).score,100);
 assert.equal(p.players.get(ids[1]).score,0);
 assert.equal(reveal.winners[0],ids[1]);
});
test("Closest Wins: server keeps target private, validates safe integer, ties correctly",()=>{
 const {p,ids,act,advance}=fixture("closest",10);
 const privateView=p.view(ids[0]).social;
 assert.ok(!Object.hasOwn(privateView,"target"));
 assert.throws(()=>act(ids[0],"respond",1.5),/integer|Invalid social response/);
 assert.throws(()=>act(ids[0],"respond",1e9),/Invalid social response|integer/);
 for(let i=0;i<10;i++)act(ids[i],"respond",i<2?88:120+i);
 assert.equal(p.players.get(ids[0]).score,100);
 assert.equal(p.players.get(ids[1]).score,100);
 assert.deepEqual(p.view(ids[2]).social.winners,["Guest 0","Guest 1"]);
 advance(45000);
 assert.equal(p.phase,"reveal");
});
test("Survey Showdown: accepted answers scored by rank; raw submissions hidden until reveal",()=>{
 const {p,ids,act}=fixture("survey",10);
 act(ids[0],"respond","passport");
 const pre=p.view("host").social;
 assert.ok(!JSON.stringify(pre).includes("passport"));
 const texts=["Toothbrush","PHONE charger","tickets","sunscreen","a wrong answer","PASSPORT","Sunscreen","not here","toothbrush"];
 ids.slice(1).forEach((id,i)=>act(id,"respond",texts[i]));
 assert.equal(p.phase,"reveal");
 assert.equal(p.players.get(ids[0]).score,100);
 assert.equal(p.players.get(ids[1]).score,80);
 assert.equal(p.players.get(ids[2]).score,60);
 assert.equal(p.players.get(ids[5]).score,0);
 const result=p.view("host").social;
 assert.equal(result.topAnswers[0].count,2);
 assert.equal(result.topAnswers[1].count,2);
});
test("Secret Impostor: only legitimate players see word; reconnect identity stable and votes host-proof",()=>{
 const {p,ids,act,advance}=fixture("impostor",20);
 assert.equal(p.phase,"clue");
 const suspect=p.social.impostorId;
 const agent=ids.find(id=>id!==suspect);
 assert.equal(p.view(suspect).social.role,"impostor");
 assert.ok(!JSON.stringify(p.view(suspect).social).includes("Pancakes"));
 assert.ok(!JSON.stringify(p.view("host").social).includes("Pancakes"));
 assert.equal(p.view(agent).social.secretWord,"Pancakes");
 p.connected(agent,false);p.connected(agent,true);
 assert.equal(p.view(agent).social.secretWord,"Pancakes");
 assert.throws(()=>act("host","respond","sneaky"),/joined players/);
 for(const id of ids)act(id,"respond","A family clue");
 assert.equal(p.phase,"voting");
 assert.ok(!JSON.stringify(p.view(suspect).social).includes("Pancakes"));
 assert.ok(!JSON.stringify(p.view("host").social).includes("Pancakes"));
 assert.throws(()=>act(agent,"respond",agent),/another active player/);
 for(const id of ids)act(id,"respond",id===suspect?agent:suspect);
 assert.equal(p.phase,"reveal");
 assert.equal(p.view("host").social.impostor,p.players.get(suspect).name);
 assert.equal(p.view("host").social.secretWord,"Pancakes");
 assert.equal(p.players.get(agent).score,100);
 assert.equal(p.players.get(suspect).score,0);
 assert.throws(()=>act(agent,"respond",suspect),/Submission closed|Unknown|locked/);
 act("host","next");
 assert.equal(p.phase,"clue");
 advance(45000);
 assert.equal(p.phase,"voting");
 advance(35000);
 assert.equal(p.phase,"reveal");
});
