test("standalone protocol rejects unknown event, extra actor, malformed social input",()=>{
 const base={v:1,type:"respond",requestId:"social-accepted",matchId:null,revision:0,value:1};
 assert.equal(validateAction(base),base);
 assert.throws(()=>validateAction({...base,actor:"host"}),/Unknown message field/);
 assert.throws(()=>validateAction({...base,value:{playerId:"spoof"}}),/Invalid social response/);
 assert.throws(()=>validateAction({...base,value:"X".repeat(81)}),/Invalid social response/);
 assert.throws(()=>validateAction({...base,type:"start",value:"unknown"}),/Unknown game mode/);
});
