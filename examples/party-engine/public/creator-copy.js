export function creatorText(key, values = {}, locale = "en") {
  if (locale === "es" && Number(values.count) === 1) {
    if (key === " · {count} questions · Edit") return " · 1 pregunta · Editar";
    if (key === "Imported {count} questions. Saved on this device. Download a JSON backup when ready.") return "Se ha importado 1 pregunta. Está guardada en este dispositivo. Descarga una copia JSON cuando termines.";
  }
  const template = locale === "es" ? (creatorSpanish[key] ?? key) : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => String(values[name] ?? placeholder));
}
// Only fixed first-party validation messages and numeric/field parameters qualify.
// Native browser diagnostics remain available in English when display language changes.
const errorTemplates = [
  "Maximum {count} questions per guest party quiz.",
  "Quiz title must contain 1–{max} printable characters.",
  "Question {number} must contain 1–{max} printable characters.",
  "Answer {number} must contain 1–{max} printable characters.",
  "A quiz needs 1–{count} questions.", "Question {number} is invalid.",
  "Question {number} needs 2–4 choices.", "Question {number}: choose the correct answer.",
  "Question {number}: explanation must be 240 characters or fewer.", "Question {number}: invalid {field}.",
  "Import at most {count} questions at a time.", "Row {number}: answer options must start at A with no gaps.",
  "You can save up to {count} local quizzes. Export and remove one first.",
  "Razzia question {number} is invalid.",
  "Razzia question {number}: only single-answer questions are supported. Multi-answer and estimation need a different game format.",
  "Razzia question {number}: media is not supported by the guest quiz editor.",
  "Razzia question {number}: choose exactly one correct answer.",
  "Razzia question {number}: custom scoring options are not supported.",
  "Razzia question {number}: answer time must be 5–120 whole seconds.",
  "Razzia question {number}: points and penalty must be whole numbers from 0 to 100,000.",
];
const escapePattern = value => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const rules = errorTemplates.map(key => {
  const names = [];
  const pattern = key.split(/(\{(?:number|max|count|field)\})/).map(part => {
    if (/^\{\w+\}$/.test(part)) { const name = part.slice(1,-1); names.push(name); return name === "field" ? "(seconds|points|penalty)" : "([0-9]+)"; }
    return escapePattern(part);
  }).join("");
  return { key, names, pattern: new RegExp("^" + pattern + "$") };
});
export function creatorError(message, name, locale = "en") {
  const fallback = "Something went wrong. Check browser storage.";
  if (locale !== "es") return message || fallback;
  if (name === "QuotaExceededError") return creatorText("Device storage is full. Export a backup and free some space.", {}, locale);
  if (Object.hasOwn(creatorSpanish, message)) return creatorSpanish[message];
  for (const rule of rules) {
    const match = rule.pattern.exec(message);
    if (!match) continue;
    const values = Object.fromEntries(rule.names.map((key,index) => [key, match[index + 1]]));
    if (values.field) values.field = { seconds:"tiempo de respuesta", points:"puntos", penalty:"penalización" }[values.field];
    return creatorText(rule.key, values, locale);
  }
  return creatorText(fallback, {}, locale);
}
