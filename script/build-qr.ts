import { transform } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

/** Keep one licensed encoder source for React and the standalone guest server. */
export async function buildQrEncoder() {
  const source = await readFile("client/src/lib/vendor/qrcodegen.ts", "utf8");
  const notice = source.match(/^\/\*[\s\S]*?\*\//)?.[0];
  if (!notice?.includes("Copyright (c) Project Nayuki")) throw new Error("QR encoder license notice missing");
  const { code } = await transform(source, { loader: "ts", format: "esm", target: "es2020", legalComments: "none" });
  await mkdir("examples/party-engine/public/vendor", { recursive: true });
  await writeFile("examples/party-engine/public/vendor/qrcodegen.js",
    notice.replace(/[ \t]+$/gm, "") + "\n// Generated by script/build-qr.ts; edit the canonical TypeScript source.\n" + code);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await buildQrEncoder();
